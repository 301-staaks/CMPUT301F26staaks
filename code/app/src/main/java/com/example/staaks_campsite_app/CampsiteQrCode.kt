package com.example.staaks_campsite_app

import android.graphics.Bitmap
import android.net.Uri
import com.google.zxing.BarcodeFormat
import com.journeyapps.barcodescanner.BarcodeEncoder

/**
 * creates and reads campsite qr codes
 */
object CampsiteQrCode {

    /**
     * builds the permanent text stored inside the qr code
     */
    fun createContent(campsiteId: String): String {
        require(
            campsiteId.isNotBlank() &&
                    "/" !in campsiteId &&
                    campsiteId != "." &&
                    campsiteId != ".."
        ) {
            "The campsite ID is invalid."
        }

        return Uri.Builder()
            .scheme("staaks")
            .authority("campsite")
            .appendPath(campsiteId)
            .build()
            .toString()
    }

    /**
     * creates the image using the campsite id
     */
    fun createImage(campsiteId: String): Bitmap {
        val content = createContent(campsiteId)

        return BarcodeEncoder().encodeBitmap(
            content,
            BarcodeFormat.QR_CODE,
            512,
            512
        )
    }

    /**
     * returns the campsite id or null when the code is invalid
     */
    fun readCampsiteId(content: String): String? {
        return try {
            val uri = Uri.parse(content)

            if (
                uri.scheme != "staaks" ||
                uri.authority != "campsite" ||
                uri.pathSegments.size != 1
            ) {
                return null
            }

            val campsiteId = uri.pathSegments[0]

            // accepts only the exact format generated by our app
            if (createContent(campsiteId) != content) {
                return null
            }

            campsiteId
        } catch (_: Exception) {
            null
        }
    }
}