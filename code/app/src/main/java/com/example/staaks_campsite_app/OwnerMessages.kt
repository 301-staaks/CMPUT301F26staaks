/**
 * The owner's messages screen, it lists conversations with guests.
 *
 * The conversations shown are placeholder data and are not loaded from the
 * database yet.
 *
 * @param navController controls navigation to other screens.
 */
@Composable
fun OwnerMessages(navController: NavController) {

    val session by SessionManager.state.collectAsState()

    Scaffold(
        topBar = { UiTopRow(navController = navController, title = "Owner Main", homeRoute = "owner_main", isAdmin = session!!.isAdmin) },
        bottomBar = { UiBottomRow(navController = navController, tabs = ownerTabs) }
    ) { innerPadding ->
        Box(
            modifier = Modifier
                .padding(innerPadding)
        ) {
            /*
            -------------------------------------------------------------------------------------------------------------------------------------
            Main Content of Page
            -------------------------------------------------------------------------------------------------------------------------------------
             */

            val conversations = listOf("Guest 1", "Guest 2", "Guest 3") // placeholder

            LazyColumn(
                modifier = Modifier
                    .fillMaxSize()
                    .padding(12.dp),
                verticalArrangement = Arrangement.spacedBy(12.dp)
            ) {
                items(conversations) { name ->
                    Card(
                        modifier = Modifier
                            .fillMaxWidth()
                            .clickable { navController.navigate("owner_conversation") }
                    ) {
                        Column(modifier = Modifier.padding(12.dp)) {
                            Text(name, fontSize = 18.sp)
                            Text("Campsite: —")
                            Text("Last message preview…", color = Color.Gray)
                        }
                    }
                }
            }
        }
    }
}
