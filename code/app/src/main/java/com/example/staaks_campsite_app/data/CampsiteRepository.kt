package com.example.staaks_campsite_app.data

import androidx.compose.runtime.mutableStateListOf
import com.example.staaks_campsite_app.data.model.Campsite
import com.example.staaks_campsite_app.data.model.User
import com.google.firebase.firestore.FirebaseFirestore

/**
 * Represents a list of campsite listings available in the system.
 * @property campsites List of campsite listings.
 * @property db Firebase Firestore instance for database operations.
 * @constructor Creates an empty campsite list.
 */
class campsiteRepository(
    private val db: FirebaseFirestore = FirebaseFirestore.getInstance()
) {
    private val campsitesRef = db.collection("campsites")

    private val _campsites = mutableStateListOf<Campsite>()

    val campsites: List<Campsite>
        get() = _campsites

    init {
        campsitesRef.addSnapshotListener { snapshot, error ->
            if (error != null) {
                return@addSnapshotListener
            }

            _campsites.clear()

            snapshot?.documents?.forEach { document ->
                val campsite = document.toObject(Campsite::class.java)
                if (campsite != null) {
                    _campsites.add(campsite)
                }
            }
        }
    }


    /**
     * generate a unique ID for a new campsite listing.
     * @return A unique ID generated by Firestore.
     */
    fun generateUniqueID(): String {
        return campsitesRef.document().id
    }

    /**
     * Retrieves a campsite by its unique ID.
     * @param owner the owner of the campsite.
     * @return The campsite with the specified ID, or null if not found.
     */
    fun getCampsitesByOwner(owner: User): List<Campsite> {
        return campsites.filter { it.owner == owner }
    }

    /**
     * Retrieves the total counts of the campsites
     * @return The total counts of the campsites
     */
    fun count(): Int {
        return campsites.size
    }

    /**
     * Creates a new campsite listing and adds it to the system.
     * @param owner The owner of the campsite.
     * @param name The name of the campsite.
     * @param location The location of the campsite.
     * @param capacity The maximum capacity of the campsite.
     * @param price The nightly price of the campsite.
     * @param date The available dates for booking.
     * @param images Optional list of images associated with the campsite.
     * @param description Optional description of the campsite.
     * @param rating Optional rating of the campsite.
     */
    fun createAndAddCampsite(
        owner: User,
        name: String,
        location: String,
        capacity: Int,
        price: Double,
        date: MutableList<String>,
        images: MutableList<String>? = null,
        description: String = "",
        rating: Double = 0.0
    ) {
        // 1. Generate unique ID from Firestore
        val autoId = campsitesRef.document().id

        // 2. Assign that ID to the Campsite object
        val campsite = Campsite(
            id = autoId,
            owner = owner,
            name = name,
            location = location,
            capacity = capacity,
            price = price,
            date = date,
            images = images,
            description = description,
            rating = rating
        )

        // 3. Save to Firestore under that exact document ID
        campsitesRef.document(campsite.id).set(campsite)
    }

    /**
     * Adds a new campsite listing to the system if the ID does not exist in the database.
     * Update if ID exist in the database.
     * @param campsite The campsite listing to be added.
     */
    fun addOrUpdateCampsite(campsite: Campsite) {
        val docId = campsite.id.ifBlank { campsitesRef.document().id }
        campsitesRef.document(docId).set(campsite)
    }

    /**
     * Deletes an existing campsite listing in the system.
     * @param campsite The campsite listing to be deleted.
     * @throws IllegalArgumentException if the campsite with the specified ID does not exist.
     */
    fun deleteCampsite(campsite: Campsite) {
        require(campsites.any { it.id == campsite.id }) {
            "Campsite with ID ${campsite.id} does not exist"
        }
        campsitesRef.document(campsite.id).delete()
    }

    /**
     * Filters campsites based on specified criteria.
     * @param location Optional location filter.
     * @param date Optional date filter.
     * @param capacity Optional capacity filter.
     * @return A list of filtered campsites.
     */
    fun filterCampsites(
        keyword: String? =null,
        location: String? = null,
        date: List<String>? = null,
        capacity: Int? = null,
    ): List<Campsite> {
        return campsites.filter { campsite ->
            val matchesKeyword = keyword.isNullOrBlank() ||
                    campsite.name.contains(keyword)
            val matchesLocation = location.isNullOrBlank() ||
                    campsite.location.contains(location, ignoreCase = true)

            val matchesGuests = capacity == null ||
                    campsite.capacity >= capacity

            val matchesDates = date.isNullOrEmpty() ||
                    campsite.date.containsAll(date)

            matchesKeyword && matchesLocation && matchesGuests && matchesDates
        }
    }
}