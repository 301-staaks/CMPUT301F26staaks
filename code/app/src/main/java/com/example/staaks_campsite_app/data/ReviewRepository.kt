package com.example.staaks_campsite_app.data

import androidx.compose.runtime.mutableStateListOf
import com.example.staaks_campsite_app.data.model.Campsite
import com.example.staaks_campsite_app.data.model.Reservation
import com.example.staaks_campsite_app.data.model.Review
import com.google.firebase.firestore.FirebaseFirestore

class ReviewRepository (
    private val db: FirebaseFirestore? = try {
        FirebaseFirestore.getInstance()
    } catch (_: IllegalStateException) {
        null
    }
) {
    private val reviewsRef = db?.collection("reviews")

    private val _reviews = mutableStateListOf<Review>()

    val reviews: List<Review>
        get() = _reviews


    /**
     * saves a review in firestore
     *
     * creates an id if the review does not have one
     *
     * @param review the review we want to save
     */

    fun saveReview(review: Review) {
        if (review.id.isBlank()) {
            review.id = reviewsRef?.document()?.id ?:""
        }

        reviewsRef?.document(review.id)
            ?.set(review)

        calculateAverageRating(review.campsiteId)
    }

    /**
     * finds the loaded reviews for a campsite
     *
     * @param campsiteId the id of the campsite
     * @return the reviews for the campsite or an empty list if none are loaded
     */

    fun getReviewsForCampsite(campsiteId: String): List<Review> {
        val result = mutableListOf<Review>()

        for (review in _reviews) {
            if (review.campsiteId == campsiteId) {
                result.add(review)
            }
        }

        return result
    }

    /**
     * generate a unique ID for a new review.
     * @return A unique ID generated by Firestore.
     */
    fun generateUniqueID(): String {
        return reviewsRef?.document()?.id ?: ""
    }


    /**
     * calculates the average rating for a campsite and sets it in firestore
     *
     * @param campsiteId the id of the campsite
     */
    fun calculateAverageRating(campsiteId: String) {
        var totalRating = 0.0
        var count = 0
        for (review in _reviews) {
            if (review.campsiteId == campsiteId) {
                totalRating += review.rating
                count++
            }
        }
        if (count > 0) {
            val averageRating = totalRating / count
            val campsiteRef = db?.collection("campsites")?.document(campsiteId)
            campsiteRef?.update("rating", averageRating)
            campsiteRef?.update("ratingCount", count)
        } else {
            val campsiteRef = db?.collection("campsites")?.document(campsiteId)
            campsiteRef?.update("rating", 0.0)
            campsiteRef?.update("ratingCount", 0)
        }
    }


    /**
     * Deletes an existing review in the system.
     * @param review The review listing to be deleted.
     * @throws IllegalArgumentException if the review with the specified ID does not exist.
     */
    fun deleteReview(review: Review) {

        var campsite = review.campsiteId


        if (review.id.isNotBlank()) {
            reviewsRef?.document(review.id)?.delete()
        }

        calculateAverageRating(campsite)
    }


    init {
        reviewsRef?.addSnapshotListener { snapshot, error ->
            if (error != null) {
                return@addSnapshotListener
            }

            _reviews.clear()

            snapshot?.documents?.forEach { document ->
                val review = document.toObject(
                    Review::class.java
                )

                if (review != null) {
                    review.id = document.id
                    _reviews.add(review)
                }
            }
        }
    }


}